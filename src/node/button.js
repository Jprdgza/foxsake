// `foxsake button install|uninstall`: sets up the "Add to Zen" button.
//  1. Registers the native helper with Zen (a small JSON file in Zen's NativeMessagingHosts folder
//     pointing to a launcher script inside this project).
//  2. Packages addon/ as an .xpi and opens Zen's install prompt.
import { chmodSync, existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, relative } from "node:path";
import { writeZip } from "../core/archive.js";
import { OUT, ROOT } from "./library.js";
import { openInZen } from "./zen.js";

const HOST_NAME = "foxsake";
const ADDON_ID = "button@foxsake";
// Zen 1.24 reads Mozilla's standard folder; Zen's own folder is kept too in case a later version
// switches. (Found by testing: registering only in Zen's folder gave "helper not found".)
const HOSTS_DIRS = [
  join(homedir(), "Library", "Application Support", "Mozilla", "NativeMessagingHosts"),
  join(homedir(), "Library", "Application Support", "zen", "NativeMessagingHosts"),
];
const LAUNCHER = join(OUT, "native", "foxsake-host.sh");

export async function installButton({ openPrompt = true } = {}) {
  mkdirSync(join(OUT, "native"), { recursive: true });
  // Zen starts helpers with a minimal PATH, so the launcher uses the absolute path of this Node.
  const q = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`; // POSIX single-quote escaping
  // Prefer a stable Node path: process.execPath can be a versioned Homebrew Cellar folder that
  // disappears on the next `brew upgrade`, which would silently break the button.
  const node = ["/opt/homebrew/bin/node", "/usr/local/bin/node"].find((p) => existsSync(p)) ?? process.execPath;
  writeFileSync(LAUNCHER, `#!/bin/sh\n# Fox Sake native helper launcher (generated by "foxsake button install").\nexec ${q(node)} ${q(join(ROOT, "src", "node", "native-host.js"))} "$@"\n`);
  chmodSync(LAUNCHER, 0o755);
  const hostJson = JSON.stringify({
    name: HOST_NAME,
    description: "Fox Sake: converts Chrome Web Store extensions for Zen",
    path: LAUNCHER,
    type: "stdio",
    allowed_extensions: [ADDON_ID],
  }, null, 2) + "\n";
  for (const dir of HOSTS_DIRS) {
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, `${HOST_NAME}.json`), hostJson);
    console.log(`✔ Registered the helper: ${join(dir, `${HOST_NAME}.json`)}`);
  }

  const files = new Map();
  const dir = join(ROOT, "addon");
  const walk = (d) => readdirSync(d).forEach((n) => {
    const full = join(d, n);
    const st = lstatSync(full);
    if (st.isSymbolicLink()) return; // never follow links out of the folder
    if (st.isDirectory()) walk(full);
    else files.set(relative(dir, full), new Uint8Array(readFileSync(full)));
  });
  walk(dir);
  const version = JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8")).version;
  const xpi = join(OUT, `foxsake-button-${version}.xpi`);
  writeFileSync(xpi, writeZip(files));
  console.log(`✔ Built ${relative(process.cwd(), xpi)}`);
  if (!openPrompt) return;
  console.log('🦊 Opening Zen\'s install prompt. Click "Add", then visit any extension on chromewebstore.google.com.');
  openInZen(xpi);
}

export async function uninstallButton() {
  for (const dir of HOSTS_DIRS) {
    const f = join(dir, `${HOST_NAME}.json`);
    if (existsSync(f)) rmSync(f);
  }
  console.log("✔ Removed the helper registration. To remove the button add-on itself: Zen → about:addons → Fox Sake: Add to Zen → Remove.");
}
